export const findModelsByMake = (make, category = null) => {
  const entry = VEHICLE_MAKES.find((m) => m.make === make);
  if (!entry) return [];
  if (!category) return entry.models.map((m) => m.name);
  return entry.models.filter((m) => m.category === category).map((m) => m.name);
};

export const getCategories = () => {
  const s = new Set();
  VEHICLE_MAKES.forEach((m) => m.models.forEach((x) => s.add(x.category)));
  return Array.from(s);
};

export const getMakesByCategory = (category) => {
  if (!category) return VEHICLE_MAKES.map((m) => m.make);
  return VEHICLE_MAKES.filter((m) => m.models.some((x) => x.category === category)).map((m) => m.make);
};

export const getModelCategory = (make, model) => {
  const entry = VEHICLE_MAKES.find((m) => m.make === make);
  if (!entry) return null;
  const found = entry.models.find((x) => String(x.name).toLowerCase() === String(model).toLowerCase());
  return found ? found.category : null;
};
